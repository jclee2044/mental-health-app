"""Local Part 3.3 browser fixture: fictional SQLite, mocked providers, no network.

Run from the project root with backend/.venv/bin/python. No .env is loaded.
The control JSON supports memory_failure, save_failure and history_failure.
Send demo:fail for a reply failure or demo:slow for a 15-second fixed reply.
Never select microphone or telephone actions in this browser evaluation.
"""
import argparse
from datetime import datetime, timezone
import http.client
import json
import os
from pathlib import Path
import sqlite3
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", type=int, default=8033)
    parser.add_argument("--directory", type=Path, default=ROOT / "tmp/part33-browser")
    args = parser.parse_args()
    directory = args.directory.resolve()
    if not directory.is_relative_to(ROOT / "tmp"):
        parser.error("Fixture data must stay under this project's tmp directory")
    directory.mkdir(parents=True, exist_ok=True)
    control = directory / "control.json"
    if not control.exists():
        control.write_text("{}\n")
    log = directory / "requests.jsonl"

    def record(**fields):
        with log.open("a") as stream:
            stream.write(json.dumps({"utc": datetime.now(timezone.utc).isoformat(), **fields}) + "\n")

    def flags():
        return json.loads(control.read_text())

    def forbidden(*_args, **_kwargs):
        record(event="blocked_outgoing_http")
        raise AssertionError("Outgoing HTTP forbidden in Part 3.3 browser fixture")

    http.client.HTTPConnection.connect = forbidden
    http.client.HTTPSConnection.connect = forbidden
    os.environ.update(OPENAI_API_KEY="fictional-browser-key", VOICE_BACKEND_MODEL="fictional-browser-model", REFRAMING_ENABLED="0")
    os.environ.pop("CHAT_REASONING_EFFORT", None)

    import uvicorn
    from fastapi.responses import JSONResponse
    from app.main import create_app
    from app.features.voice.provider import ProviderUnavailable
    from app.features.voice.settings import VoiceSettings

    class MockProvider:
        def reply_text(self, message, history=(), context=None):
            record(event="mock_reply", message=message, memory_present=bool(context and context.personal.data))
            if message.strip().lower() == "demo:fail":
                raise ProviderUnavailable()
            if message.strip().lower() == "demo:slow":
                time.sleep(15)
            return "[Mocked evaluation reply — not generated by a model] This fictional reply remains available even when optional personal memory fails."

        def summarize_title(self, _context):
            record(event="mock_title")
            return "Mock: Fictional evaluation conversation"

        def summarize_memory(self, _context):
            record(event="mock_summary")
            return '{"substantive":false,"summary":""}'

        def create_session(self, *_args):
            raise ProviderUnavailable()

        def end_session(self, *_args):
            raise ProviderUnavailable()

        def transcribe(self, *_args, **_kwargs):
            raise ProviderUnavailable()

    app = create_app(directory / "fictional.sqlite3")
    app.state.voice_settings = VoiceSettings(api_key="fictional-browser-key", backend_model="fictional-browser-model")
    app.state.voice_provider = MockProvider()
    select = app.state.personal_memory.select

    def select_memory(*args, **kwargs):
        if flags().get("memory_failure"):
            record(event="injected_memory_failure")
            raise sqlite3.OperationalError("Fictional injected memory failure")
        return select(*args, **kwargs)

    app.state.personal_memory.select = select_memory

    @app.middleware("http")
    async def fixture_requests(request, call_next):
        started = time.monotonic()
        mode = flags()
        path = request.url.path
        block_save = mode.get("save_failure") and request.method == "PUT" and path.startswith(("/api/sessions/", "/api/entries/", "/api/chat/conversations/"))
        block_history = mode.get("history_failure") and request.method == "GET" and path.startswith(("/api/sessions", "/api/entries", "/api/chat/conversations"))
        if block_save or block_history:
            response = JSONResponse(status_code=503, content={"error": {"code": "storage_unavailable", "message": "Fictional evaluation storage failure.", "fields": {}}})
        else:
            response = await call_next(request)
        if path.startswith("/api/"):
            record(event="request", method=request.method, path=path, status=response.status_code, elapsed_ms=round((time.monotonic() - started) * 1000, 2))
        return response

    record(event="fixture_start", port=args.port, database="fictional.sqlite3", outgoing_http="forbidden")
    uvicorn.run(app, host="127.0.0.1", port=args.port)
    record(event="fixture_stop")


if __name__ == "__main__":
    main()
