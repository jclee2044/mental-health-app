"""Local evidence rehearsal with explicitly mocked text, never a provider call.

Run with backend/.venv/bin/python scripts/serve_submission_demo.py.
Uses a separate, ignored SQLite file. Production still uses app.main and real
server configuration. No environment files or credentials are needed here.
"""
import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))


def demo_app():
    from app.main import create_app
    from app.features.voice.settings import VoiceSettings
    from app.features.voice.provider import ProviderUnavailable

    class MockProvider:
        def reply_text(self, message, history):
            if message.strip().lower() == "demo:fail":
                raise ProviderUnavailable()
            return ("[Mocked demonstration reply — not generated by a model] "
                    "Guided breathing uses a 3–2–1 countdown, then six cycles of "
                    "four seconds in and six seconds out. Open Guided breathing "
                    "from Home when you choose. You can pause or end at any time.")

        def create_session(self, *args):
            raise ProviderUnavailable()  # Never send audio or SDP to a provider.

        def end_session(self, *args):
            raise ProviderUnavailable()

    app = create_app(ROOT / "backend" / "data" / "submission-demo.sqlite3")
    app.state.voice_settings = VoiceSettings(api_key="unused-demo", backend_model="mocked-demo")
    app.state.voice_provider = MockProvider()
    return app


if __name__ == "__main__":
    import uvicorn
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", type=int, default=8001)
    args = parser.parse_args()
    print("MOCKED TEXT ONLY. No model contribution is established by this demo.")
    print("SQLite: backend/data/submission-demo.sqlite3 (separate from still.sqlite3)")
    uvicorn.run(demo_app(), host="127.0.0.1", port=args.port)
